"""SQLite storage for customer feedback.

All queries use parameter binding. User-provided text is never concatenated
into SQL. The only dynamic SQL fragments (WHERE clauses) are built from fixed
strings chosen by this module, and the values are always passed as parameters.
"""
from __future__ import annotations

import sqlite3
from contextlib import contextmanager
from pathlib import Path
from typing import Any, Iterator, Sequence

import config

SCHEMA = """
CREATE TABLE IF NOT EXISTS feedback (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    review_text     TEXT    NOT NULL CHECK (length(trim(review_text)) > 0),
    product         TEXT,
    rating          INTEGER CHECK (rating IS NULL OR rating BETWEEN 1 AND 5),
    sentiment_label TEXT    CHECK (sentiment_label IS NULL
                                   OR sentiment_label IN ('positive', 'neutral', 'negative')),
    score_positive  REAL,
    score_neutral   REAL,
    score_negative  REAL,
    topics          TEXT,
    source          TEXT    NOT NULL DEFAULT 'manual',
    created_at      TEXT    NOT NULL,
    model_version   TEXT,
    extra           TEXT    CHECK (extra IS NULL OR json_valid(extra)),
    batch_id        TEXT,
    flags           TEXT
);

CREATE INDEX IF NOT EXISTS idx_feedback_created_at ON feedback (created_at);
CREATE INDEX IF NOT EXISTS idx_feedback_sentiment  ON feedback (sentiment_label);
CREATE INDEX IF NOT EXISTS idx_feedback_product    ON feedback (product);

CREATE TABLE IF NOT EXISTS import_batches (
    batch_id    TEXT PRIMARY KEY,
    filename    TEXT,
    imported_at TEXT NOT NULL,
    row_count   INTEGER NOT NULL,
    mapping     TEXT
);
"""

# Columns added after Module 2. Databases created earlier get them through init_db()'s migration,
# which only ever ADDS columns, so existing reviews are never changed or lost.
_MIGRATION_COLUMNS = {
    "extra": "TEXT CHECK (extra IS NULL OR json_valid(extra))",
    "batch_id": "TEXT",
    "flags": "TEXT",
}
_POST_MIGRATION_SQL = "CREATE INDEX IF NOT EXISTS idx_feedback_batch ON feedback (batch_id);"

# Columns accepted by insert functions (id is generated by SQLite).
INSERT_COLUMNS = (
    "review_text",
    "product",
    "rating",
    "sentiment_label",
    "score_positive",
    "score_neutral",
    "score_negative",
    "topics",
    "source",
    "created_at",
    "model_version",
    "extra",
    "batch_id",
    "flags",
)

# Columns the UI may sort by. Mapping keeps user input out of ORDER BY.
SORT_COLUMNS = {
    "newest": "created_at DESC, id DESC",
    "oldest": "created_at ASC, id ASC",
    "rating_high": "rating DESC, id DESC",
    "rating_low": "rating ASC, id ASC",
    # "worst" / "best" reviews: rating first (reviews without a rating last), then how strongly the model judged them
    "worst": "(rating IS NULL), rating ASC, score_negative DESC, created_at DESC, id DESC",
    "best": "(rating IS NULL), rating DESC, score_positive DESC, created_at DESC, id DESC",
}


def _resolve_path(db_path: str | Path | None) -> Path:
    return Path(db_path) if db_path is not None else Path(config.DB_PATH)


@contextmanager
def get_connection(db_path: str | Path | None = None) -> Iterator[sqlite3.Connection]:
    """Open a connection, commit on success, roll back on error, always close."""
    path = _resolve_path(db_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(path)
    conn.row_factory = sqlite3.Row
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def init_db(db_path: str | Path | None = None) -> None:
    """Create the tables if needed and add any columns an older database is missing."""
    with get_connection(db_path) as conn:
        conn.executescript(SCHEMA)
        existing = {row["name"] for row in conn.execute("PRAGMA table_info(feedback)")}
        for column, definition in _MIGRATION_COLUMNS.items():
            if column not in existing:
                conn.execute(f"ALTER TABLE feedback ADD COLUMN {column} {definition}")
        conn.execute(_POST_MIGRATION_SQL)


def _row_values(record: dict[str, Any]) -> tuple:
    return tuple(record.get(col) for col in INSERT_COLUMNS)


_INSERT_SQL = (
    f"INSERT INTO feedback ({', '.join(INSERT_COLUMNS)}) "
    f"VALUES ({', '.join('?' for _ in INSERT_COLUMNS)})"
)

# Same insert, but skipped when an identical review already exists.
_INSERT_UNIQUE_SQL = (
    f"INSERT INTO feedback ({', '.join(INSERT_COLUMNS)}) "
    f"SELECT {', '.join('?' for _ in INSERT_COLUMNS)} "
    "WHERE NOT EXISTS ("
    "  SELECT 1 FROM feedback "
    "  WHERE review_text = ? AND COALESCE(product, '') = COALESCE(?, '') AND created_at = ?"
    ")"
)


def insert_review(record: dict[str, Any], db_path: str | Path | None = None) -> int:
    """Insert one validated review and return its new id."""
    with get_connection(db_path) as conn:
        cur = conn.execute(_INSERT_SQL, _row_values(record))
        return int(cur.lastrowid)


def insert_reviews(
    records: Sequence[dict[str, Any]],
    db_path: str | Path | None = None,
    skip_duplicates: bool = True,
) -> tuple[int, int]:
    """Insert many validated reviews in a single transaction.

    Returns (inserted, skipped_duplicates). A duplicate is a row with the same
    review_text, product and created_at as one already stored.
    """
    inserted = 0
    with get_connection(db_path) as conn:
        for record in records:
            if skip_duplicates:
                params = _row_values(record) + (
                    record.get("review_text"),
                    record.get("product"),
                    record.get("created_at"),
                )
                cur = conn.execute(_INSERT_UNIQUE_SQL, params)
            else:
                cur = conn.execute(_INSERT_SQL, _row_values(record))
            inserted += cur.rowcount
    return inserted, len(records) - inserted


def _escape_like(text: str) -> str:
    return text.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")


def _build_where(
    date_from: str | None,
    date_to: str | None,
    product: str | None,
    sentiment: str | None,
    search: str | Sequence[str] | None,
    extra_key: str | None = None,
    extra_value: str | None = None,
    flag: str | None = None,
    batch_id: str | None = None,
    topic: str | None = None,
    exclude_topics: Sequence[str] | None = None,
) -> tuple[str, list[Any]]:
    clauses: list[str] = []
    params: list[Any] = []
    for name in (exclude_topics or [])[:8]:  # "leave out delivery": reviews tagged with that topic are skipped
        if "," in name:
            raise ValueError(f"invalid topic: {name!r}")
        clauses.append("instr(',' || COALESCE(topics, '') || ',', ?) = 0")
        params.append(f",{name},")
    if topic:
        if "," in topic:
            raise ValueError(f"invalid topic: {topic!r}")
        clauses.append("instr(',' || COALESCE(topics, '') || ',', ?) > 0")
        params.append(f",{topic},")
    if extra_key and extra_value is not None:
        clauses.append("json_extract(extra, ?) = ?")
        params.extend([_json_path(extra_key), str(extra_value)])
    if flag:
        if flag not in KNOWN_FLAGS:
            raise ValueError(f"unknown flag: {flag!r}")
        clauses.append("instr(',' || COALESCE(flags, '') || ',', ?) > 0")
        params.append(f",{flag},")
    if batch_id:
        clauses.append("batch_id = ?")
        params.append(batch_id)
    if date_from:
        clauses.append("date(created_at) >= date(?)")
        params.append(date_from)
    if date_to:
        clauses.append("date(created_at) <= date(?)")
        params.append(date_to)
    if product:
        clauses.append("product = ?")
        params.append(product)
    if sentiment:
        if sentiment == "unanalyzed":
            clauses.append("sentiment_label IS NULL")
        else:
            clauses.append("sentiment_label = ?")
            params.append(sentiment)
    terms = [search] if isinstance(search, str) else list(search or [])
    terms = [t.strip() for t in terms if t and t.strip()][:5]
    if terms:
        # any of the terms may appear in the review text or the product name
        parts = []
        for term in terms:
            parts.append("(review_text LIKE ? ESCAPE '\\' OR COALESCE(product, '') LIKE ? ESCAPE '\\')")
            like = f"%{_escape_like(term)}%"
            params.extend([like, like])
        clauses.append("(" + " OR ".join(parts) + ")")
    where = f"WHERE {' AND '.join(clauses)}" if clauses else ""
    return where, params


def fetch_reviews(
    *,
    date_from: str | None = None,
    date_to: str | None = None,
    product: str | None = None,
    sentiment: str | None = None,
    search: str | Sequence[str] | None = None,
    extra_key: str | None = None,
    extra_value: str | None = None,
    flag: str | None = None,
    batch_id: str | None = None,
    topic: str | None = None,
    exclude_topics: Sequence[str] | None = None,
    sort: str = "newest",
    page: int = 1,
    page_size: int = config.DEFAULT_PAGE_SIZE,
    db_path: str | Path | None = None,
) -> tuple[list[dict[str, Any]], int]:
    """Return (rows_for_page, total_matching_rows).

    Dates are 'YYYY-MM-DD' strings and are inclusive. `sentiment` may be a label
    or 'unanalyzed' for rows without a prediction yet. `extra_key`/`extra_value`
    filter on a custom CSV column kept in the review's `extra` data, `flag` on a
    quality flag ('low_confidence', 'truncated') and `batch_id` on one upload, `topic` on one topic tag.
    """
    page = max(1, int(page))
    page_size = max(1, min(int(page_size), 500))
    order_by = SORT_COLUMNS.get(sort, SORT_COLUMNS["newest"])
    where, params = _build_where(
        date_from, date_to, product, sentiment, search, extra_key, extra_value, flag, batch_id, topic, exclude_topics
    )

    with get_connection(db_path) as conn:
        total = conn.execute(f"SELECT COUNT(*) FROM feedback {where}", params).fetchone()[0]
        rows = conn.execute(
            f"SELECT * FROM feedback {where} ORDER BY {order_by} LIMIT ? OFFSET ?",
            [*params, page_size, (page - 1) * page_size],
        ).fetchall()
    return [dict(r) for r in rows], int(total)


def get_review(review_id: int, db_path: str | Path | None = None) -> dict[str, Any] | None:
    with get_connection(db_path) as conn:
        row = conn.execute("SELECT * FROM feedback WHERE id = ?", (review_id,)).fetchone()
    return dict(row) if row else None


def delete_review(review_id: int, db_path: str | Path | None = None) -> bool:
    """Delete one review by id. Returns True if a row was removed."""
    with get_connection(db_path) as conn:
        return conn.execute("DELETE FROM feedback WHERE id = ?", (int(review_id),)).rowcount > 0


def latest_review_id(source: str | None = None, db_path: str | Path | None = None) -> int | None:
    """Id of the most recently added review, optionally only those with a given source (e.g. 'chat')."""
    sql = "SELECT id FROM feedback" + (" WHERE source = ?" if source else "") + " ORDER BY id DESC LIMIT 1"
    with get_connection(db_path) as conn:
        row = conn.execute(sql, (source,) if source else ()).fetchone()
    return int(row[0]) if row else None


def count_reviews(db_path: str | Path | None = None) -> int:
    with get_connection(db_path) as conn:
        return int(conn.execute("SELECT COUNT(*) FROM feedback").fetchone()[0])


def get_products(db_path: str | Path | None = None) -> list[str]:
    """Distinct non-empty product names, alphabetically (for filter dropdowns)."""
    with get_connection(db_path) as conn:
        rows = conn.execute(
            "SELECT DISTINCT product FROM feedback "
            "WHERE product IS NOT NULL AND product <> '' ORDER BY product COLLATE NOCASE"
        ).fetchall()
    return [r[0] for r in rows]


def get_date_range(db_path: str | Path | None = None) -> tuple[str | None, str | None]:
    """Earliest and latest review dates as 'YYYY-MM-DD', or (None, None) if empty."""
    with get_connection(db_path) as conn:
        row = conn.execute(
            "SELECT date(MIN(created_at)), date(MAX(created_at)) FROM feedback"
        ).fetchone()
    return row[0], row[1]


