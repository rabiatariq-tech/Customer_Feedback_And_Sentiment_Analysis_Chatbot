_SENTIMENT_COLUMNS = (
    "sentiment_label",
    "score_positive",
    "score_neutral",
    "score_negative",
    "model_version",
    "flags",
)
_UPDATE_SENTIMENT_SQL = (
    "UPDATE feedback SET "
    + ", ".join(f"{col} = ?" for col in _SENTIMENT_COLUMNS)
    + " WHERE id = ?"
)


def update_sentiments(
    updates: Sequence[tuple[int, dict[str, Any]]],
    db_path: str | Path | None = None,
) -> int:
    """Store sentiment results for many reviews in one transaction.

    ``updates`` is a list of (review_id, fields) where fields holds the sentiment
    columns (see ``SentimentResult.to_record_fields``). The original review text is
    never modified. Returns the number of rows updated.
    """
    changed = 0
    with get_connection(db_path) as conn:
        for review_id, fields in updates:
            params = tuple(fields.get(col) for col in _SENTIMENT_COLUMNS) + (int(review_id),)
            changed += conn.execute(_UPDATE_SENTIMENT_SQL, params).rowcount
    return changed


def update_sentiment(review_id: int, fields: dict[str, Any], db_path: str | Path | None = None) -> bool:
    return update_sentiments([(review_id, fields)], db_path) == 1


def fetch_texts(
    *,
    after_id: int = 0,
    limit: int = 100,
    only_pending: bool = True,
    db_path: str | Path | None = None,
) -> list[tuple[int, str]]:
    """Return (id, review_text) pairs with id > after_id, oldest id first.

    Keyset paging (``after_id``) lets callers walk the table in batches without
    re-reading rows. ``only_pending`` restricts to reviews with no sentiment yet.
    """
    limit = max(1, min(int(limit), 1000))
    sql = "SELECT id, review_text FROM feedback WHERE id > ?"
    if only_pending:
        sql += " AND sentiment_label IS NULL"
    sql += " ORDER BY id LIMIT ?"
    with get_connection(db_path) as conn:
        rows = conn.execute(sql, (int(after_id), limit)).fetchall()
    return [(int(r["id"]), r["review_text"]) for r in rows]


def count_by_sentiment(db_path: str | Path | None = None) -> dict[str, int]:
    """Counts per label, with 'unanalyzed' for reviews that have no label yet."""
    counts = {"positive": 0, "neutral": 0, "negative": 0, "unanalyzed": 0}
    with get_connection(db_path) as conn:
        rows = conn.execute(
            "SELECT COALESCE(sentiment_label, 'unanalyzed') AS label, COUNT(*) AS n "
            "FROM feedback GROUP BY label"
        ).fetchall()
    for row in rows:
        counts[row["label"]] = int(row["n"])
    return counts


# ---------------------------------------------------------------------------
# Flexible CSV imports: custom ("extra") columns and upload batches
# ---------------------------------------------------------------------------
KNOWN_FLAGS = ("low_confidence", "truncated")


def _json_path(key: str) -> str:
    """JSON path for one top-level key, e.g. branch -> $."branch". Rejects keys that could break out of the path."""
    if not key or any(ch in key for ch in '"\\') or any(ord(ch) < 32 for ch in key):
        raise ValueError(f"invalid extra-column name: {key!r}")
    return f'$."{key}"'


def get_extra_keys(db_path: str | Path | None = None) -> list[dict[str, Any]]:
    """Custom columns present in the data: [{'key', 'rows', 'distinct_values'}], alphabetical."""
    with get_connection(db_path) as conn:
        rows = conn.execute(
            "SELECT j.key AS key, COUNT(*) AS n_rows, COUNT(DISTINCT j.value) AS n_values "
            "FROM feedback, json_each(feedback.extra) AS j "
            "WHERE feedback.extra IS NOT NULL "
            "GROUP BY j.key ORDER BY j.key COLLATE NOCASE"
        ).fetchall()
    return [{"key": r["key"], "rows": int(r["n_rows"]), "distinct_values": int(r["n_values"])} for r in rows]


def get_extra_values(key: str, limit: int = 50, db_path: str | Path | None = None) -> list[tuple[str, int]]:
    """Most common values of one custom column as (value, count), for filter dropdowns."""
    path = _json_path(key)
    limit = max(1, min(int(limit), 500))
    with get_connection(db_path) as conn:
        rows = conn.execute(
            "SELECT json_extract(extra, ?) AS v, COUNT(*) AS n FROM feedback "
            "WHERE json_extract(extra, ?) IS NOT NULL GROUP BY v ORDER BY n DESC, v LIMIT ?",
            (path, path, limit),
        ).fetchall()
    return [(str(r["v"]), int(r["n"])) for r in rows]


def insert_batch(
    batch_id: str,
    filename: str | None,
    row_count: int,
    mapping: dict[str, Any] | None = None,
    db_path: str | Path | None = None,
) -> None:
    """Record one CSV upload (which file, when, how many rows, which columns were used)."""
    import json
    from datetime import datetime

    with get_connection(db_path) as conn:
        conn.execute(
            "INSERT INTO import_batches (batch_id, filename, imported_at, row_count, mapping) VALUES (?, ?, ?, ?, ?)",
            (
                batch_id,
                filename,
                datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
                int(row_count),
                json.dumps(mapping) if mapping else None,
            ),
        )


def list_batches(db_path: str | Path | None = None) -> list[dict[str, Any]]:
    with get_connection(db_path) as conn:
        rows = conn.execute("SELECT * FROM import_batches ORDER BY imported_at DESC, batch_id").fetchall()
    return [dict(r) for r in rows]


