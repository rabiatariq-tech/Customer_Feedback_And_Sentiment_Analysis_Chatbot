def fetch_untagged(
    *, after_id: int = 0, limit: int = 200, db_path: str | Path | None = None
) -> list[tuple[int, str]]:
    """(id, review_text) for reviews whose topics have not been set yet (topics IS NULL)."""
    limit = max(1, min(int(limit), 1000))
    with get_connection(db_path) as conn:
        rows = conn.execute(
            "SELECT id, review_text FROM feedback WHERE id > ? AND topics IS NULL ORDER BY id LIMIT ?",
            (int(after_id), limit),
        ).fetchall()
    return [(int(r["id"]), r["review_text"]) for r in rows]


def update_topics(updates: Sequence[tuple[int, str]], db_path: str | Path | None = None) -> int:
    """Store topic tags for many reviews in one transaction. Review text is never modified."""
    changed = 0
    with get_connection(db_path) as conn:
        for review_id, topics in updates:
            changed += conn.execute(
                "UPDATE feedback SET topics = ? WHERE id = ?", (topics, int(review_id))
            ).rowcount
    return changed
